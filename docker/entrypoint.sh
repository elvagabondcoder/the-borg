#!/usr/bin/env bash
# Docker entrypoint. Materializes config.sh from environment variables (set
# via docker-compose's env_file/environment, ultimately from .env), so the
# rest of the suite — lib/common.sh's load_config and everything built on
# it — runs completely unmodified whether it's invoked from a host crontab
# or from here.
#
# After writing config.sh it runs the preflight doctor check, does one
# immediate pass so `docker compose up` shows output right away instead of
# waiting for the first cron tick, then hands off to crond for the
# recurring schedule.
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_FILE="$REPO_ROOT/config.sh"

: "${VAULT_IDEAS_DIR:=/vault/ideas}"
: "${STATE_DIR:=/state}"

cat >"$CONFIG_FILE" <<EOF
# Generated by docker/entrypoint.sh from environment variables at container
# start. Do not edit by hand — edit .env on the host instead.
VAULT_IDEAS_DIR="${VAULT_IDEAS_DIR}"
STATE_DIR="${STATE_DIR}"
CRON_SCHEDULE="${CRON_SCHEDULE:-*/30 * * * *}"
CLAUDE_MODEL="${CLAUDE_MODEL:-}"
CLAUDE_EXTRA_ARGS=(${CLAUDE_EXTRA_ARGS:-})
MAX_IDEAS_PER_RUN="${MAX_IDEAS_PER_RUN:-5}"
CLAUDE_TIMEOUT_SECONDS="${CLAUDE_TIMEOUT_SECONDS:-180}"
MAX_RETRIES="${MAX_RETRIES:-1}"
MAX_CONTEXT_CHARS="${MAX_CONTEXT_CHARS:-60000}"
TODO_FILENAME="${TODO_FILENAME:-TODO.md}"
QUESTIONS_FILENAME="${QUESTIONS_FILENAME:-QUESTIONS.md}"
DONE_SENTINEL_FILENAME="${DONE_SENTINEL_FILENAME:-.idea-done}"
ARCHIVE_ON_DONE="${ARCHIVE_ON_DONE:-false}"
ARCHIVE_DIR="${ARCHIVE_DIR:-$(dirname "${VAULT_IDEAS_DIR}")/Archive}"
LOG_RETENTION_DAYS="${LOG_RETENTION_DAYS:-30}"
EOF

echo "Generated $CONFIG_FILE:"
cat "$CONFIG_FILE"
echo

if [ -z "${ANTHROPIC_API_KEY:-}" ] && [ -z "${CLAUDE_CODE_OAUTH_TOKEN:-}" ]; then
	echo "WARNING: neither ANTHROPIC_API_KEY nor CLAUDE_CODE_OAUTH_TOKEN is set." >&2
	echo "The claude CLI will fail to authenticate. Set one of them in .env." >&2
fi

"$REPO_ROOT/bin/the-borg-doctor.sh"

echo
echo "Running one pass now, then handing off to cron on schedule \"${CRON_SCHEDULE:-*/30 * * * *}\"..."
"$REPO_ROOT/bin/the-borg-run.sh" || true

mkdir -p "$STATE_DIR/logs"
CRON_LOG="$STATE_DIR/logs/cron-stdout.log"
echo "${CRON_SCHEDULE:-*/30 * * * *} cd $REPO_ROOT && ./bin/the-borg-run.sh >> \"$CRON_LOG\" 2>&1" >/etc/crontabs/root

exec crond -f -d 8
